export function generateDeterministicWaveform(seed: number, bars = 96): number[] {
  const peaks: number[] = [];
  for (let i = 0; i < bars; i++) {
    const t = i / bars;
    const envelope = Math.sin(t * Math.PI) * 0.65 + 0.35;
    const harmonic =
      Math.abs(Math.sin((i + seed * 7) * 0.42)) * 0.5 +
      Math.abs(Math.cos((i * 1.7 + seed * 3) * 0.28)) * 0.35 +
      0.15;
    peaks.push(Number(Math.min(1, Math.max(0.08, envelope * harmonic)).toFixed(3)));
  }
  return peaks;
}

